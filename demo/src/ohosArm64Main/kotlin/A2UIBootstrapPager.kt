package com.tencent.kuikly.a2ui.demo.pages

import com.tencent.kuikly.a2ui.bridge.A2UIOhosPager
import com.tencent.kuikly.core.annotations.Page

/**
 * A2UIBootstrapPager — registers the "a2ui" page route into the `:demo`
 * KMP output so that A2UISurfaceView.ets (which starts a Kuikly page with
 * `pageName:'a2ui'`) can find a Pager creator when the host app links the
 * `:demo` shared library.
 *
 * Why this exists:
 * - `A2UISurfaceView.ets` in `a2ui-render-ohos` always boots the KMP side
 *   with `pageName:'a2ui'`; the KMP side must therefore have a Pager
 *   registered under that exact name.
 * - The `:a2ui` module registers `"a2ui" → A2UIOhosPager` directly from
 *   its own `A2UIKuiklyEntry.kt#initKuikly()`, which works for standalone
 *   apps (ohosAppForNativePage, ohosAppForTest) that link `:a2ui`.
 * - The `:demo` module has its `initKuikly()` generated by KSP from
 *   `@Page(...)` annotations, so we need a `@Page("a2ui")`-annotated class
 *   to end up in the KSP-generated route table. Apps that link `:demo`
 *   (ohosAppForKuiklyPage, ohosAppForBothPages) rely on this to render any
 *   Native-page-embedded `A2UISurfaceView`.
 *
 * The subclass adds no behaviour — all bootstrap logic lives in
 * [A2UIOhosPager]. It exists purely to give KSP a `@Page("a2ui")` symbol to
 * pick up.
 */
@Page("a2ui")
class A2UIBootstrapPager : A2UIOhosPager()
