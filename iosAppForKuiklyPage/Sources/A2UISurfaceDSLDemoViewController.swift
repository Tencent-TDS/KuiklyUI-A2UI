import UIKit
import OpenKuiklyIOSRender
import OpenA2UIIOSRender

/// iOS mirror of `androidAppForKuiklyPage/A2UISurfaceDSLDemoActivity`.
///
/// Hosts the Kuikly DSL page `A2UISurfaceDemo` (see `:demo/…/
/// A2UISurfaceDemoPager.kt`) inside a plain `UIViewController` via
/// `KuiklyRenderViewControllerBaseDelegator`. The Kuikly DSL page itself
/// embeds `A2UISurface { … }` children directly in its Flex tree — proving
/// out the *Kuikly-page → A2UI* integration path.
///
/// ### Wiring
/// 1. `A2UIKuiklyRenderViewSupport.prepareForKuiklyPageHosting()` is called
///    once so any A2UI custom render view (from `A2UICustomComponentDemo`)
///    reaches the KMP-side registry. This is the iOS counterpart of Android's
///    `A2UIKuiklyBaseViewSupport.wrap(...)` call.
/// 2. `KuiklyRenderViewControllerBaseDelegator` is initialised with
///    pageName `A2UISurfaceDemo`. The delegate's `fetchContextCodeWithPageName`
///    returns `A2UIDemo` — the framework name generated by the
///    `:demo` cocoapods block (see `a2ui/demo/a2ui_demo.podspec`).
/// 3. On `viewDidLoad`, the delegator's `viewDidLoadWithView:` mounts the
///    Kuikly render tree inside `container`, which is a full-bleed subview
///    of the VC.
final class A2UISurfaceDSLDemoViewController: UIViewController {

    private static let pageName = "A2UISurfaceDemo"

    private var delegator: KuiklyRenderViewControllerBaseDelegator?
    private let container = UIView()

    // MARK: - Lifecycle

    override func viewDidLoad() {
        super.viewDidLoad()

        // Populate the KMP-side A2UICustomViewRegistry *and* force-run the
        // @Page registry warm-up for `A2UISurfaceDemo`. The two-argument
        // overload is idempotent and safe to call on every KuiklyPage host
        // VC; it protects against the race where any earlier A2UI code path
        // (sibling demo VC, icon / custom-component / custom-function
        // registration, native-hosted A2UISurfaceView, …) flips
        // `BridgeManager.isDidInit()` to `true` and causes Kuikly's
        // generated entry to skip page registration — otherwise
        // `createPager("A2UISurfaceDemo")` crashes with
        // `PagerNotFoundException` on the context thread.
        A2UIKuiklyRenderViewSupport.prepareForKuiklyPageHosting(
            pageName: Self.pageName,
            frameworkName: "A2UIDemo"
        )

        title = "[DSL] A2UI in Kuikly Page"
        view.backgroundColor = UIColor(red: 245/255.0, green: 245/255.0, blue: 245/255.0, alpha: 1.0)

        setupContainer()
        setupDelegator()
    }

    override func viewDidLayoutSubviews() {
        super.viewDidLayoutSubviews()
        delegator?.viewDidLayoutSubviews()
    }

    override func viewWillAppear(_ animated: Bool) {
        super.viewWillAppear(animated)
        delegator?.viewWillAppear()
    }

    override func viewDidAppear(_ animated: Bool) {
        super.viewDidAppear(animated)
        delegator?.viewDidAppear()
    }

    override func viewWillDisappear(_ animated: Bool) {
        super.viewWillDisappear(animated)
        delegator?.viewWillDisappear()
    }

    override func viewDidDisappear(_ animated: Bool) {
        super.viewDidDisappear(animated)
        delegator?.viewDidDisappear()
    }

    // MARK: - Setup

    private func setupContainer() {
        container.translatesAutoresizingMaskIntoConstraints = false
        container.backgroundColor = UIColor(white: 0.96, alpha: 1.0)
        view.addSubview(container)
        NSLayoutConstraint.activate([
            container.topAnchor.constraint(equalTo: view.safeAreaLayoutGuide.topAnchor),
            container.leadingAnchor.constraint(equalTo: view.leadingAnchor),
            container.trailingAnchor.constraint(equalTo: view.trailingAnchor),
            container.bottomAnchor.constraint(equalTo: view.bottomAnchor),
        ])
    }

    private func setupDelegator() {
        let d = KuiklyRenderViewControllerBaseDelegator(
            pageName: Self.pageName,
            pageData: [:]
        )
        d.delegate = self
        delegator = d
        d.viewDidLoad(with: container)
    }
}

// MARK: - KuiklyRenderViewControllerBaseDelegatorDelegate

extension A2UISurfaceDSLDemoViewController: KuiklyRenderViewControllerBaseDelegatorDelegate {

    /// Tell Kuikly which KMP-compiled framework hosts the `A2UISurfaceDemo`
    /// pageName. `A2UIDemo` matches the `baseName` declared by the
    /// `cocoapods { framework { baseName = "A2UIDemo" } }` block in
    /// `:demo/build.2.1.21.gradle.kts`.
    func fetchContextCode(withPageName pageName: String,
                          resultCallback callback: @escaping KuiklyContextCodeCallback) {
        callback("A2UIDemo", nil)
    }

    func createLoadingView() -> UIView {
        let v = UIView()
        v.backgroundColor = .white
        return v
    }

    func createErrorView() -> UIView {
        let v = UIView()
        v.backgroundColor = .white
        return v
    }
}
